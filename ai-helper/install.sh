#!/bin/sh
# Registers the Bob helper with Chrome-family browsers so the Dev Dashboard can ask Bob Shell.
#   sh ai-helper/install.sh              install or repair (re-run after moving the folder or changing Node)
#   sh ai-helper/install.sh --uninstall  remove it
set -eu

NAME="com.devdashboard.bob"
EXTENSION_ID="ogpphggbmdgamakbhoikiejheaihopbo" # unpacked, pinned by the `key` in manifest.json
STORE_ID="kkfeeieiijlklgllbahnppmefcfcahkm"     # Chrome Web Store
HERE=$(cd "$(dirname "$0")" && pwd)
HOST_DIR="$HOME/.dev-dashboard"
LAUNCHER="$HOST_DIR/bob-host"

case "$(uname -s)" in
  Darwin)
    BASE="$HOME/Library/Application Support"
    DIRS="Google/Chrome
Google/Chrome Beta
Google/Chrome Canary
Chromium
Microsoft Edge
BraveSoftware/Brave-Browser
Arc/User Data
Vivaldi"
    ;;
  Linux)
    BASE="$HOME/.config"
    DIRS="google-chrome
google-chrome-beta
chromium
microsoft-edge
BraveSoftware/Brave-Browser
vivaldi"
    ;;
  *)
    echo "Only macOS and Linux are supported." >&2
    exit 1
    ;;
esac

# One browser profile folder per line (some contain spaces).
for_each_browser() {
  printf '%s\n' "$DIRS" | while IFS= read -r dir; do
    [ -n "$dir" ] && "$@" "$BASE/$dir"
  done
}

remove_manifest() {
  rm -f "$1/NativeMessagingHosts/$NAME.json"
}

if [ "${1:-}" = "--uninstall" ]; then
  for_each_browser remove_manifest
  rm -rf "$HOST_DIR"
  echo "Removed the Bob helper."
  exit 0
fi

NODE=$(command -v node || true)
BOB=$(command -v bob || true)
[ -n "$NODE" ] || { echo "Node.js not found. Install Node 20+ and run this again." >&2; exit 1; }
[ -n "$BOB" ] || { echo "Bob Shell not found. Install it (https://bob.ibm.com/docs/shell) and run this again." >&2; exit 1; }
# Resolve npm's symlink so the helper can run Bob's script with this exact Node.
BOB_REAL=$(cd "$(dirname "$BOB")" && "$NODE" -e 'console.log(require("fs").realpathSync(process.argv[1]))' "$BOB")

mkdir -p "$HOST_DIR"
cat >"$LAUNCHER" <<EOF
#!/bin/sh
# Generated by ai-helper/install.sh — re-run it instead of editing.
DD_BOB='$BOB_REAL' exec '$NODE' '$HERE/bob-host.js' "\$@"
EOF
chmod 755 "$LAUNCHER"

MANIFEST=$(cat <<EOF
{
  "name": "$NAME",
  "description": "Lets Dev Dashboard ask Bob Shell",
  "path": "$LAUNCHER",
  "type": "stdio",
  "allowed_origins": ["chrome-extension://$EXTENSION_ID/", "chrome-extension://$STORE_ID/"]
}
EOF
)

write_manifest() {
  [ -d "$1" ] || return 0
  mkdir -p "$1/NativeMessagingHosts"
  printf '%s\n' "$MANIFEST" >"$1/NativeMessagingHosts/$NAME.json"
  echo "  ✓ ${1#"$BASE"/}"
}
echo "Registered for:"
for_each_browser write_manifest

echo
echo "Bob Shell: $("$NODE" "$BOB_REAL" --version 2>/dev/null | head -1) at $BOB_REAL"
echo "Done. Open a new tab, then Settings → Bob to paste your Bob API key."
